/**
 * Writers for every output. All of them work from one representation per
 * drawing (Lucide's icon nodes, and the optimized tagsets variants), so a
 * vanilla SVG, a sprite symbol, a tile and a React, Vue or React Native
 * component can never disagree about what they draw.
 */
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { EFFECT_NAMES, type Motion } from '../runtime/motion.ts';
import { WEIGHTS } from '../runtime/weights.ts';
import { normalizeCode } from '../runtime/resolve.ts';
import { exportNames, type Icon } from './lucide.ts';
import { ROOT, ROOT_ATTRS, type Glyph, type Node, type Tagset, type Variant } from './source.ts';
import { tileSvg } from './tiles.ts';

/** A tagsets glyph with its variants' nodes optimized for shipping (and their maxStroke). */
export interface Built {
  glyph: Glyph;
  fixed?: Variant;
  hug: Variant;
}

/** A Lucide icon with the heaviest stroke it takes, and how it animates. */
export interface BuiltIcon {
  icon: Icon;
  maxStroke?: number;
  /** Its own animation, from the first upstream that has one (UNA, then lucide-animated). */
  motion?: Motion;
  motionSource?: 'una' | 'lucide-animated';
  /** lucide-animated's export name for it and its animation there (if it carried over), for the lucide-animated drop-in. */
  lucideAnimated?: { name: string; motion?: Motion };
}

export type Framework = 'react' | 'vue' | 'react-native';
const FRAMEWORKS: readonly Framework[] = ['react', 'vue', 'react-native'];

const GENERATED = '// Generated by scripts/build.ts. Do not edit: change sources/ (or bump lucide-static) and rebuild.\n';

function write(file: string, content: string) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
}

const attr = (a: Record<string, string>) => Object.entries(a).map(([k, v]) => `${k}="${v}"`).join(' ');
const el = ([tag, a]: Node) => `<${tag} ${attr(a)}/>`;
const viewBox = (v: Variant) => `${v.x} 0 ${v.width} 24`;
const STROKE_ATTRS = Object.fromEntries(Object.entries(ROOT_ATTRS).filter(([k]) => !['xmlns', 'width', 'height', 'viewBox'].includes(k)));
const defaultVariant = (b: Built) => b.fixed ?? b.hug;

/** A short, stable fingerprint of a drawing, so reports can tell a redraw from a rename. */
export const geometry = (nodes: readonly Node[]) => createHash('sha256').update(JSON.stringify(nodes)).digest('hex').slice(0, 12);

export function variantSvg(glyph: Glyph, v: Variant, extra: Record<string, string> = {}): string {
  const root = { ...ROOT_ATTRS, width: String(v.width), viewBox: viewBox(v), class: `xymbol xymbol-${glyph.id}`, ...extra };
  return `<svg ${attr(root)}>${v.nodes.map(el).join('')}</svg>`;
}

export function iconSvg(icon: Icon, extra: Record<string, string> = {}): string {
  const root = { ...ROOT_ATTRS, class: ['lucide', `lucide-${icon.name}`, ...icon.aliases.map((a) => `lucide-${a.name}`)].join(' '), ...extra };
  return `<svg ${attr(root)}>${icon.nodes.map(el).join('')}</svg>`;
}

function sprite(built: readonly Built[], icons: readonly BuiltIcon[], pick: (b: Built) => Variant): string {
  const symbols = [
    ...icons.map(({ icon }) => `<symbol id="${icon.name}" viewBox="0 0 24 24" ${attr(STROKE_ATTRS)}>${icon.nodes.map(el).join('')}</symbol>`),
    ...built.map((b) => {
      const v = pick(b);
      return `<symbol id="${b.glyph.id}" viewBox="${viewBox(v)}" ${attr(STROKE_ATTRS)}>${v.nodes.map(el).join('')}</symbol>`;
    }),
  ];
  return `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${symbols.join('\n')}\n</svg>\n`;
}

/** For JSDoc `@preview`: the drawing in black on white, which editors show on hover. */
const dataUri = (svg: string) => `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
const PREVIEW = { stroke: '#000', style: 'background-color: #fff; border-radius: 2px' };

/** The heaviest named weight at or under a stroke, for docs. */
const weightAt = (stroke: number) => Object.entries(WEIGHTS).filter(([, s]) => s <= stroke).at(-1)?.[0] ?? 'regular';
const weightsDoc = (maxStroke: number | undefined) =>
  maxStroke === undefined ? 'Takes every weight.' : `Heavier weights stop at stroke ${maxStroke} (${weightAt(maxStroke)}), where its strokes would crowd.`;

// ---------------------------------------------------------------- tagsets glyphs

function meta({ glyph }: Built) {
  return { id: glyph.id, name: glyph.name, tagset: glyph.tagset.id, code: glyph.meta.code, label: glyph.meta.label, component: glyph.component };
}

/** What each variant shows, in words, for docs and the manifest. */
function shows(v: Variant, glyph: Glyph): string {
  if (v.from === 'drawn') return 'a drawing';
  return `"${v.from === 'short' ? glyph.meta.short : glyph.meta.text}"`;
}

function glyphDoc(b: Built): string {
  const { glyph } = b;
  const also = glyph.meta.aliases?.length ? `\n * Also resolves: ${glyph.meta.aliases.join(', ')}.` : '';
  const fits = b.fixed
    ? `Fixed: ${shows(b.fixed, glyph)}; hug: ${shows(b.hug, glyph)}, ${b.hug.width} wide.`
    : `Hug only: ${shows(b.hug, glyph)}, ${b.hug.width} wide; no form fits the square.`;
  const preview = dataUri(variantSvg(glyph, defaultVariant(b), PREVIEW));
  return `/**\n * ${glyph.meta.label}: \`${glyph.meta.code}\` in ${glyph.tagset.label.toLowerCase()} (${glyph.tagset.standard}).${also}\n * ${fits} ${weightsDoc(defaultVariant(b).maxStroke)}\n *\n * @preview ![${glyph.meta.code}](${preview})\n */\n`;
}

const variantLiteral = (v: Variant, node: string) => `{ x: ${v.x}, width: ${v.width}, node: ${node}${v.maxStroke === undefined ? '' : `, maxStroke: ${v.maxStroke}`} }`;
const sameNodes = (a: Variant, b: Variant) => JSON.stringify(a.nodes) === JSON.stringify(b.nodes);

/** `const node = ...;` declarations and the fixed/hug expressions, sharing node data where the variants draw the same. */
function variantsCode(b: Built): { decls: string; fixed: string; hug: string } {
  const decls = [];
  let fixed = 'null';
  if (b.fixed) {
    decls.push(`const fixedNode = ${JSON.stringify(b.fixed.nodes)} as const;`);
    fixed = variantLiteral(b.fixed, 'fixedNode');
  }
  let hugNode = 'fixedNode';
  if (!b.fixed || !sameNodes(b.fixed, b.hug)) {
    decls.push(`const hugNode = ${JSON.stringify(b.hug.nodes)} as const;`);
    hugNode = 'hugNode';
  }
  return { decls: decls.join('\n'), fixed, hug: variantLiteral(b.hug, hugNode) };
}

function registry(tagsets: readonly Tagset[], built: readonly Built[]): string {
  const sets = tagsets.map((t) => {
    const keys: Record<string, string> = {};
    for (const { glyph } of built.filter((b) => b.glyph.tagset === t)) {
      for (const code of [glyph.meta.code, ...(glyph.meta.aliases ?? [])]) keys[normalizeCode(code, t.normalize)] = glyph.component;
    }
    return `  ${JSON.stringify(t.id)}: { normalize: ${JSON.stringify(t.normalize)}, keys: ${JSON.stringify(keys)} },`;
  });
  const info = tagsets.map((t) => ({ id: t.id, prefix: t.prefix, label: t.label, standard: t.standard, ...(t.url ? { url: t.url } : {}), count: built.filter((b) => b.glyph.tagset === t).length }));
  return `${GENERATED}import type { Registry } from './resolve.js';
import type { TagsetInfo } from './types.js';

export type TagsetId = ${tagsets.map((t) => JSON.stringify(t.id)).join(' | ')};

export const tagsets: readonly TagsetInfo[] = ${JSON.stringify(info, null, 2)};

export const registry: Registry = {
${sets.join('\n')}
};
`;
}

/**
 * Copy the shared runtime (icon builder, weights, resolver, render arithmetic, motion, types) into a
 * package's src/generated/, and the web animation engine into the web packages'.
 */
function runtime(pkgSrc: string, web: boolean) {
  mkdirSync(join(pkgSrc, 'generated'), { recursive: true });
  for (const dir of ['scripts/runtime', ...(web ? ['scripts/runtime-web'] : [])]) {
    const from = join(ROOT, dir);
    for (const f of readdirSync(from)) copyFileSync(join(from, f), join(pkgSrc, 'generated', f));
  }
}

/** React, Vue and React Native: one module per glyph (deep-importable) plus a barrel. */
function glyphComponents(pkg: Framework, tagsets: readonly Tagset[], built: readonly Built[]) {
  const src = join(ROOT, 'packages', pkg, 'src');
  for (const b of built) {
    const v = variantsCode(b);
    write(
      join(src, 'generated/glyphs', `${b.glyph.id}.ts`),
      `${GENERATED}import { createGlyph } from '../../createGlyph.js';

${v.decls}

${glyphDoc(b)}export const ${b.glyph.component} = /* @__PURE__ */ createGlyph(
  ${JSON.stringify(meta(b))},
  ${v.fixed},
  ${v.hug},
);

export default ${b.glyph.component};
`,
    );
  }
  write(join(src, 'generated/glyphs/index.ts'), GENERATED + built.map((b) => `export { ${b.glyph.component} } from './${b.glyph.id}.js';`).join('\n') + '\n');
  write(join(src, 'generated/registry.ts'), registry(tagsets, built));
}

/** Vanilla: plain glyph data objects in one module (object literals tree-shake as they are). */
function vanillaGlyphs(tagsets: readonly Tagset[], built: readonly Built[]) {
  const src = join(ROOT, 'packages/vanilla/src');
  const body = built.map((b) => {
    const v = variantsCode(b);
    const scoped = v.decls.replace(/const (fixed|hug)Node/g, (_, w: string) => `const ${b.glyph.component}_${w}`);
    const ref = (s: string) => s.replace(/(fixed|hug)Node/g, (_, w: string) => `${b.glyph.component}_${w}`);
    return `${scoped}\n${glyphDoc(b)}export const ${b.glyph.component}: GlyphData = { ...${JSON.stringify(meta(b))}, fixed: ${ref(v.fixed)}, hug: ${ref(v.hug)} };`;
  });
  write(join(src, 'generated/glyphs.ts'), `${GENERATED}import type { GlyphData } from './types.js';\n\n${body.join('\n\n')}\n`);
  write(join(src, 'generated/registry.ts'), registry(tagsets, built));
}

// ---------------------------------------------------------------- Lucide icons

/** Lucide's icon data object, as lucide-react's icon modules export it (`__iconData`). */
function iconData({ icon, maxStroke }: BuiltIcon) {
  return {
    name: icon.name,
    size: 24,
    node: icon.nodes,
    ...(icon.aliases.length ? { aliases: icon.aliases.map((a) => a.name) } : {}),
    ...(maxStroke === undefined ? {} : { maxStroke }),
  };
}

function iconDoc(b: BuiltIcon): string {
  const { icon } = b;
  const aliases = [...new Set(icon.aliases.map((a) => a.component))].filter((c) => c !== icon.component);
  const also = aliases.length ? ` Also exported as ${aliases.map((c) => `\`${c}\``).join(', ')}.` : '';
  const preview = dataUri(iconSvg(icon, PREVIEW));
  return `/**\n * ${icon.component}: Lucide's \`${icon.name}\`.${also} ${weightsDoc(b.maxStroke)}\n *\n * @preview ![${icon.name}](${preview})\n * @see https://lucide.dev/icons/${icon.name}\n */\n`;
}

/** Every component name an icon is exported under: its own and its aliases', three ways each. */
export function iconExports(icon: Icon): string[] {
  return [...new Set([icon.component, ...icon.aliases.map((a) => a.component)].flatMap(exportNames))];
}

/** Every component name, without the `Icon`/`Lucide` forms: vanilla's exports and its `icons` object. */
const plainNames = (icon: Icon) => [...new Set([icon.component, ...icon.aliases.map((a) => a.component)])];

function iconComponents(pkg: Framework, icons: readonly BuiltIcon[]) {
  const src = join(ROOT, 'packages', pkg, 'src');
  for (const b of icons) {
    write(
      join(src, 'generated/icons', `${b.icon.name}.ts`),
      `${GENERATED}import { createLucideIcon } from '../../createIcon.js';
import type { IconData } from '../icon.js';

export const __iconData: IconData = ${JSON.stringify(iconData(b))};

${iconDoc(b)}const ${b.icon.component} = /* @__PURE__ */ createLucideIcon(__iconData);

export default ${b.icon.component};
`,
    );
  }
  const barrel = icons.map(({ icon }) => `export { ${iconExports(icon).map((n) => `default as ${n}`).join(', ')} } from './${icon.name}.js';`);
  write(join(src, 'generated/icons/index.ts'), GENERATED + barrel.join('\n') + '\n');
  // The `icons` object, as lucide-react's: one entry per icon, aliases left out.
  const object = icons.map(({ icon }) => `export { default as ${icon.component} } from './icons/${icon.name}.js';`);
  write(join(src, 'generated/icons-object.ts'), GENERATED + object.join('\n') + '\n');
  if (pkg === 'react') {
    const entries = icons.flatMap(({ icon }) => [icon.name, ...icon.aliases.map((a) => a.name)].map((name) => `  ${JSON.stringify(name)}: () => import('./icons/${icon.name}.js'),`));
    write(
      join(src, 'generated/dynamic-imports.ts'),
      `${GENERATED}/** Every icon and alias name to a loader for its module, as lucide-react's dynamicIconImports. */
const dynamicIconImports = {
${entries.sort().join('\n')}
} as const;

export default dynamicIconImports;
`,
    );
  }
}

/** Vanilla: each icon is Lucide's node array, as the lucide package exports it; one module per icon. */
function vanillaIcons(icons: readonly BuiltIcon[]) {
  const src = join(ROOT, 'packages/vanilla/src');
  for (const b of icons) {
    const node = JSON.stringify(b.icon.nodes);
    const value = b.maxStroke === undefined ? `${node} as const` : `/* @__PURE__ */ withMaxStroke(${node} as const, ${b.maxStroke})`;
    write(
      join(src, 'generated/icons', `${b.icon.name}.ts`),
      `${GENERATED}${b.maxStroke === undefined ? '' : "import { withMaxStroke } from '../icon.js';\n"}import type { IconNode } from '../icon.js';

${iconDoc(b)}const ${b.icon.component}: IconNode = ${value};

export default ${b.icon.component};
`,
    );
  }
  const barrel = icons.map(({ icon }) => `export { ${plainNames(icon).map((n) => `default as ${n}`).join(', ')} } from './${icon.name}.js';`);
  write(join(src, 'generated/icons/index.ts'), GENERATED + barrel.join('\n') + '\n');
}

// ---------------------------------------------------------------- animated icons

const SOURCE_NAMES = { una: 'UNA', 'lucide-animated': 'lucide-animated' } as const;

/** Data as TypeScript: JSON, except that a track repeating forever keeps its Infinity. */
const code = (value: unknown) => JSON.stringify(value, (_, v) => (v === Infinity ? '__Infinity__' : v)).replace(/"__Infinity__"/g, 'Infinity');

function animatedDoc(b: BuiltIcon): string {
  const own = b.motionSource ? `Its own animation (\`effect="auto"\`, the default) comes from ${SOURCE_NAMES[b.motionSource]}.` : 'It has no animation of its own yet, so `effect="auto"` wiggles it.';
  return `/**\n * ${b.icon.component}, animated: Lucide's \`${b.icon.name}\`. ${own} Every icon also takes ${EFFECT_NAMES.map((e) => `\`${e}\``).join(', ')}.\n *\n * @see https://lucide.dev/icons/${b.icon.name}\n */\n`;
}

/** React, Vue, React Native: an animated component per icon, built on its static module's data. */
function animatedComponents(pkg: Framework, icons: readonly BuiltIcon[]) {
  const src = join(ROOT, 'packages', pkg, 'src');
  for (const b of icons) {
    const motion = b.motion ? `\nexport const __motion: Motion = ${code(b.motion)};\n` : '';
    write(
      join(src, 'generated/animated', `${b.icon.name}.ts`),
      `${GENERATED}import { createAnimatedIcon } from '../../createAnimatedIcon.js';
${b.motion ? "import type { Motion } from '../motion.js';\n" : ''}import { __iconData } from '../icons/${b.icon.name}.js';
${motion}
${animatedDoc(b)}const ${b.icon.component} = /* @__PURE__ */ createAnimatedIcon(__iconData${b.motion ? ', __motion' : ''});

export default ${b.icon.component};
`,
    );
  }
  const barrel = icons.map(({ icon }) => `export { ${iconExports(icon).map((n) => `default as ${n}`).join(', ')} } from './${icon.name}.js';`);
  write(join(src, 'generated/animated/index.ts'), GENERATED + barrel.join('\n') + '\n');
}

/** React: lucide-animated's exports, each drawing today's Lucide with lucide-animated's own animation. */
function lucideAnimatedEntry(icons: readonly BuiltIcon[]) {
  const src = join(ROOT, 'packages/react/src');
  const imported = icons.filter((b) => b.lucideAnimated).sort((a, b) => a.lucideAnimated!.name.localeCompare(b.lucideAnimated!.name));
  const lines = imported.flatMap((b) => {
    const { name, motion } = b.lucideAnimated!;
    return [
      `import { __iconData as ${b.icon.component}Data } from './icons/${b.icon.name}.js';`,
      `/** lucide-animated's \`${name}\`, drawing Lucide's current \`${b.icon.name}\`. */`,
      `export const ${name} = /* @__PURE__ */ createLucideAnimatedIcon(${b.icon.component}Data${motion ? `, ${code(motion)}` : ''});`,
      `export type ${name}Handle = LucideAnimatedIconHandle;`,
    ];
  });
  write(
    join(src, 'generated/lucide-animated.ts'),
    `${GENERATED}import { createLucideAnimatedIcon } from '../lucideAnimated.js';\nimport type { LucideAnimatedIconHandle } from '../lucideAnimated.js';\n\n${lines.join('\n')}\n`,
  );
}

/** Vanilla: each icon's animated data (its Lucide data plus motion), for xymbols/animated. */
function vanillaAnimated(icons: readonly BuiltIcon[]) {
  const src = join(ROOT, 'packages/vanilla/src');
  for (const b of icons) {
    write(
      join(src, 'generated/animated', `${b.icon.name}.ts`),
      `${GENERATED}import type { AnimatedIconData } from '../motion.js';

${animatedDoc(b)}const ${b.icon.component}: AnimatedIconData = ${code({ ...iconData(b), ...(b.motion ? { motion: b.motion } : {}) })};

export default ${b.icon.component};
`,
    );
  }
  const barrel = icons.map(({ icon }) => `export { ${plainNames(icon).map((n) => `default as ${n}`).join(', ')} } from './${icon.name}.js';`);
  write(join(src, 'generated/animated/index.ts'), GENERATED + barrel.join('\n') + '\n');
}

// ---------------------------------------------------------------- vanilla assets

/** Vanilla dist assets: SVG files, sprites, tiles and the manifest. */
function vanillaAssets(tagsets: readonly Tagset[], built: readonly Built[], icons: readonly BuiltIcon[], versions: Versions) {
  const dist = join(ROOT, 'packages/vanilla/dist');
  const file = (fit: string, b: Built) => `svg/${fit}/${b.glyph.tagset.id}/${b.glyph.name}.svg`;
  for (const { icon } of icons) write(join(dist, 'svg/icons', `${icon.name}.svg`), iconSvg(icon) + '\n');
  for (const b of built) {
    if (b.fixed) write(join(dist, file('fixed', b)), variantSvg(b.glyph, b.fixed) + '\n');
    write(join(dist, file('hug', b)), variantSvg(b.glyph, b.hug) + '\n');
    write(join(dist, 'tiles', b.glyph.tagset.id, `${b.glyph.name}.svg`), tileSvg(b.glyph, defaultVariant(b)));
  }
  write(join(dist, 'sprite.svg'), sprite(built, icons, defaultVariant));
  write(join(dist, 'sprite-hug.svg'), sprite(built, icons, (b) => b.hug));

  const manifest = {
    description:
      'xymbols: every Lucide icon (svg/icons/) and the tagsets glyphs for standardized metadata codes. Icons are 24x24. Glyphs are 24 tall in two fits: fixed (the 24x24 square, svg/fixed/) where their content or a short form fits, and hug (as wide as the content, svg/hug/). Weights are stroke widths; maxStroke is where a drawing stops getting heavier. Plus sprites and 72x72 tiles for glyphs.',
    version: versions.version,
    lucide: versions.lucide,
    upstreams: { una: versions.una, 'lucide-animated': versions.lucideAnimated },
    effects: EFFECT_NAMES,
    grid: { height: 24, strokeWidth: 2, strokeLinecap: 'round', strokeLinejoin: 'round', padding: 1, tile: 72 },
    weights: WEIGHTS,
    sprites: { 'sprite.svg': 'icons, and glyphs fixed (or hug where there is no fixed form)', 'sprite-hug.svg': 'icons, and glyphs hug' },
    icons: icons.map(({ icon, maxStroke, motion, motionSource, lucideAnimated }) => ({
      name: icon.name,
      component: icon.component,
      ...(icon.aliases.length ? { aliases: icon.aliases.map((a) => a.name) } : {}),
      tags: icon.tags,
      svg: `svg/icons/${icon.name}.svg`,
      ...(maxStroke === undefined ? {} : { maxStroke }),
      geometry: geometry(icon.nodes),
      ...(motion ? { animation: { source: motionSource, motion: createHash('sha256').update(JSON.stringify(motion)).digest('hex').slice(0, 12) } } : {}),
      ...(lucideAnimated ? { lucideAnimated: lucideAnimated.name } : {}),
    })),
    tagsets: tagsets.map((t) => ({
      id: t.id,
      prefix: t.prefix,
      label: t.label,
      description: t.description,
      standard: t.standard,
      ...(t.url ? { url: t.url } : {}),
      normalize: t.normalize,
      frame: t.frame ?? 'none',
      count: built.filter((b) => b.glyph.tagset === t).length,
    })),
    glyphs: built.map((b) => {
      const { glyph } = b;
      const variant = (fit: 'fixed' | 'hug', v: Variant) => ({
        svg: file(fit, b),
        width: v.width,
        ...(v.x ? { x: v.x } : {}),
        shows: v.from === 'drawn' ? 'drawing' : v.from === 'short' ? glyph.meta.short : glyph.meta.text,
        ...(v.maxStroke === undefined ? {} : { maxStroke: v.maxStroke }),
        geometry: geometry(v.nodes),
      });
      return {
        id: glyph.id,
        name: glyph.name,
        tagset: glyph.tagset.id,
        component: glyph.component,
        code: glyph.meta.code,
        label: glyph.meta.label,
        ...(glyph.meta.aliases?.length ? { aliases: glyph.meta.aliases } : {}),
        ...(glyph.meta.keywords?.length ? { keywords: glyph.meta.keywords } : {}),
        frame: glyph.frame,
        fixed: b.fixed ? variant('fixed', b.fixed) : null,
        hug: variant('hug', b.hug),
        tile: `tiles/${glyph.tagset.id}/${glyph.name}.svg`,
        ...(glyph.meta.credit ? { credit: glyph.meta.credit } : {}),
      };
    }),
  };
  write(join(dist, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
}

export interface Versions {
  version: string;
  lucide: string;
  /** The UNA commit the animations come from. */
  una: string;
  lucideAnimated: string;
}

export function emitAll(tagsets: readonly Tagset[], built: readonly Built[], icons: readonly BuiltIcon[], versions: Versions, animateCss: string) {
  vanillaAssets(tagsets, built, icons, versions);
  vanillaGlyphs(tagsets, built);
  vanillaIcons(icons);
  vanillaAnimated(icons);
  write(join(ROOT, 'packages/vanilla/dist/animate.css'), animateCss);
  runtime(join(ROOT, 'packages/vanilla/src'), true);
  for (const pkg of FRAMEWORKS) {
    glyphComponents(pkg, tagsets, built);
    iconComponents(pkg, icons);
    animatedComponents(pkg, icons);
    runtime(join(ROOT, 'packages', pkg, 'src'), pkg !== 'react-native');
  }
  lucideAnimatedEntry(icons);
}
